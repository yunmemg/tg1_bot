CATALOGS = {"zh": ZH, "en": EN}


def normalize_language(language_code: object) -> str:
    """Map Telegram language codes to one of the supported languages."""
    if language_code is None:
        return DEFAULT_LANGUAGE
    value = str(language_code).strip().lower().replace("_", "-")
    if not value:
        return DEFAULT_LANGUAGE
    return "zh" if value == "zh" or value.startswith("zh-") else "en"


def _fields(template: str) -> set[str]:
    return {
        field_name.split(".", 1)[0].split("[", 1)[0]
        for _, field_name, _, _ in Formatter().parse(template)
        if field_name
    }


def validate_catalogs() -> None:
    expected = set(ZH)
    if set(EN) != expected:
        missing = sorted(expected - set(EN))
        extra = sorted(set(EN) - expected)
        raise RuntimeError(f"locale key mismatch: missing={missing}, extra={extra}")
    for key in expected:
        if _fields(ZH[key]) != _fields(EN[key]):
            raise RuntimeError(f"locale placeholder mismatch: {key}")


def t(language: str, key: str, **values: object) -> str:
    language = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    try:
        template = CATALOGS[language][key]
    except KeyError as error:
        raise KeyError(f"unknown localization key: {key}") from error
    return template.format(**values)


